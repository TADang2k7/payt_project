import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sn
from sklearn.impute import SimpleImputer
from sklearn.model_selection import train_test_split, GridSearchCV
from sklearn.preprocessing import StandardScaler, OrdinalEncoder, OneHotEncoder
from sklearn.pipeline import Pipeline
from sklearn.compose import ColumnTransformer
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score

data = pd.read_csv('StudentScore.xls')

sn.set_theme(style="whitegrid")

# Biểu đồ 1: Phân phối điểm thi môn Toán (Target Distribution)
plt.figure(figsize=(8, 5))
sn.histplot(data["math score"], kde=True, color='royalblue', bins=25)
plt.title("Phân phối điểm thi môn Toán (Math Score Distribution)")
plt.xlabel("Điểm Toán")
plt.ylabel("Số lượng học sinh")
plt.tight_layout()
plt.savefig("1_math_score_distribution.png")
plt.close()

# Biểu đồ 2: Ma trận tương quan giữa các biến số (Correlation Heatmap)
plt.figure(figsize=(7, 5))
num_cols = ["reading score", "writing score", "math score"]
corr_matrix = data[num_cols].corr()
sn.heatmap(corr_matrix, annot=True, cmap="coolwarm", fmt=".2f", square=True)
plt.title("Ma trận tương quan giữa các điểm số")
plt.tight_layout()
plt.savefig("2_score_correlation_heatmap.png")
plt.close()

# Biểu đồ 3: Phân tán giữa Writing Score và Math Score theo Giới tính
plt.figure(figsize=(8, 6))
sn.scatterplot(
    data=data,
    x="writing score",
    y="math score",
    hue="gender",
    alpha=0.7,
    palette="Set2"
)
plt.title("Tương quan giữa Điểm Viết và Điểm Toán theo Giới tính")
plt.xlabel("Writing Score")
plt.ylabel("Math Score")
plt.tight_layout()
plt.savefig("3_writing_vs_math_by_gender.png")
plt.close()

# Biểu đồ 4: Điểm Toán theo Trình độ học vấn của phụ huynh (Boxplot)
plt.figure(figsize=(10, 6))
education_order = [
    "some high school", "high school", "some college",
    "associate's degree", "bachelor's degree", "master's degree"
]
sn.boxplot(
    data=data,
    x="parental level of education",
    y="math score",
    order=education_order,
    palette="Blues"
)
plt.xticks(rotation=25)
plt.title("Phân bố Điểm Toán theo Trình độ học vấn của phụ huynh")
plt.xlabel("Trình độ học vấn phụ huynh")
plt.ylabel("Điểm Toán")
plt.tight_layout()
plt.savefig("4_math_by_parental_education.png")
plt.close()

target = "math score"
x = data.drop(target, axis=1)
y = data[target]

x_train, x_test, y_train, y_test = train_test_split(x, y, train_size=0.8, random_state=42)

num_transformer = Pipeline(steps=[
    ('imputer', SimpleImputer(strategy='median')),
    ('scaler', StandardScaler())
])

education_values = ["some high school", "high school", "some college", "associate's degree", "bachelor's degree", "master's degree"]
gender_values = ["male", "female"]
lunch_values = x_train["lunch"].unique()
test_values = x_train["test preparation course"].unique()

ord_transformer = Pipeline(steps=[
    ('imputer', SimpleImputer(strategy='most_frequent')),
    ('encoder', OrdinalEncoder(categories=[education_values, gender_values, lunch_values, test_values]))
])

nom_transformer = Pipeline(steps=[
    ('imputer', SimpleImputer(strategy='most_frequent')),
    ('encoder', OneHotEncoder())
])

preprocessor = ColumnTransformer(transformers=[
    ('num_features', num_transformer, ["reading score", "writing score"]),
    ('ordinal_features', ord_transformer, ["parental level of education", "gender", "lunch", "test preparation course"]),
    ('nomimal_features', nom_transformer, ["race/ethnicity"])
])

reg = Pipeline(steps=[
    ('preprocessor', preprocessor),
    ('regressor', RandomForestRegressor(random_state=42))
])

parameters = {
    "regressor__n_estimators": [50, 100, 200],
    "regressor__criterion": ["squared_error", "absolute_error"]
}

model = GridSearchCV(reg, param_grid=parameters, scoring='r2', cv=5, verbose=1, n_jobs=-1)
model.fit(x_train, y_train)

print(f"Tham số tốt nhất: {model.best_params_}")
print(f"R2 score tốt nhất (CV): {model.best_score_:.4f}")

# Dự đoán trên tập kiểm thử
best_model = model.best_estimator_
y_predict = best_model.predict(x_test)

print(f"MAE trên tập Test: {mean_absolute_error(y_test, y_predict):.4f}")
print(f"MSE trên tập Test: {mean_squared_error(y_test, y_predict):.4f}")
print(f"R2 trên tập Test: {r2_score(y_test, y_predict):.4f}")


# Biểu đồ 5: So sánh giá trị Thực tế vs Dự đoán (Actual vs Predicted)
plt.figure(figsize=(7, 7))
plt.scatter(y_test, y_predict, color='crimson', alpha=0.6, edgecolors='k')
# Vẽ đường chéo lý tưởng y = x (nếu dự đoán đúng tuyệt đối các điểm sẽ nằm trên đường này)
min_val = min(y_test.min(), y_predict.min())
max_val = max(y_test.max(), y_predict.max())
plt.plot([min_val, max_val], [min_val, max_val], color='black', linestyle='--', linewidth=1.5)
plt.title(f"Giá trị thực tế vs Dự đoán (R² = {r2_score(y_test, y_predict):.2f})")
plt.xlabel("Điểm thực tế (Actual)")
plt.ylabel("Điểm dự đoán (Predicted)")
plt.tight_layout()
plt.savefig("5_actual_vs_predicted.png")
plt.close()

# Biểu đồ 6: Phân phối sai số (Residual Plot)
residuals = y_test - y_predict
plt.figure(figsize=(8, 5))
sn.histplot(residuals, kde=True, color='purple', bins=20)
plt.axvline(x=0, color='red', linestyle='--')
plt.title("Phân phối sai số dự đoán (Residuals = Actual - Predicted)")
plt.xlabel("Sai số (Residual)")
plt.ylabel("Tần suất")
plt.tight_layout()
plt.savefig("6_residuals_distribution.png")
plt.close()

# Biểu đồ 7: Mức độ quan trọng của các đặc trưng (Feature Importances)
ohe_feature_names = best_model.named_steps['preprocessor'] \
    .named_transformers_['nomimal_features'] \
    .named_steps['encoder'] \
    .get_feature_names_out(["race/ethnicity"])

all_feature_names = (
    ["reading score", "writing score"] +
    ["parental level of education", "gender", "lunch", "test preparation course"] +
    list(ohe_feature_names)
)

importances = best_model.named_steps['regressor'].feature_importances_
feature_imp_df = pd.DataFrame({
    'Feature': all_feature_names,
    'Importance': importances
}).sort_values('Importance', ascending=False)

plt.figure(figsize=(10, 6))
sn.barplot(data=feature_imp_df, x='Importance', y='Feature', palette='viridis')
plt.title("Mức độ quan trọng của các đặc trưng trong Random Forest")
plt.xlabel("Độ quan trọng (Importance)")
plt.tight_layout()
plt.savefig("7_feature_importance.png")
plt.close()

print("Đã xuất toàn bộ 7 biểu đồ trực quan hóa ra file ảnh thành công.")

